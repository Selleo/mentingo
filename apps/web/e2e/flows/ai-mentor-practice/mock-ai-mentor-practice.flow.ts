import { DASHBOARD_WIDGET_SIZES, DASHBOARD_WIDGET_TYPES } from "@repo/shared";

import {
  AI_MENTOR_PRACTICE_EVALUATION,
  AI_MENTOR_PRACTICE_ID,
  AI_MENTOR_PRACTICE_THREAD_ID,
  QUEUED_AI_MENTOR_PRACTICE,
  READY_AI_MENTOR_PRACTICE,
} from "../../data/ai-mentor-practice/ai-mentor-practice.data";
import { mockDashboardFlow } from "../dashboard/mock-dashboard.flow";

import type { Page, Route } from "@playwright/test";

const fulfillJson = (route: Route, body: unknown) =>
  route.fulfill({ status: 200, contentType: "application/json", json: { data: body } });

/** Answers only `method` requests to `pathname`; other methods fall through to later routes. */
const mockEndpoint = (
  page: Page,
  method: "GET" | "POST",
  pathname: string,
  handler: (route: Route) => Promise<void>,
) =>
  page.route(
    (url) => url.pathname === pathname,
    (route) => (route.request().method() === method ? handler(route) : route.fallback()),
  );

/**
 * Practice scenarios are generated by an LLM, so creating one needs OpenAI: the dashboard shows
 * only the practice widget and the practice endpoints answer with a queued session.
 */
export const mockAiMentorPracticeDashboardFlow = (page: Page) =>
  mockDashboardFlow(page, {
    widgets: [
      {
        type: DASHBOARD_WIDGET_TYPES.AI_MENTOR_PRACTICE,
        size: DASHBOARD_WIDGET_SIZES.TWO_BY_TWO,
        visible: true,
      },
    ],
    responses: [
      { path: "/api/ai/practice", method: "POST", body: { data: QUEUED_AI_MENTOR_PRACTICE } },
      {
        path: `/api/ai/practice/${AI_MENTOR_PRACTICE_ID}`,
        body: { data: QUEUED_AI_MENTOR_PRACTICE },
      },
    ],
  });

/**
 * Mocks a ready practice and its LLM boundary (transcript, judge, replay). The replay response
 * is held until `releaseReplay` is called so the loading state can be asserted.
 */
export const mockAiMentorPracticeSessionFlow = async (page: Page) => {
  let currentPractice = { ...READY_AI_MENTOR_PRACTICE };
  let releaseReplay = () => {};
  const replayReleased = new Promise<void>((resolve) => {
    releaseReplay = resolve;
  });

  await mockEndpoint(page, "GET", `/api/ai/practice/${AI_MENTOR_PRACTICE_ID}`, (route) =>
    fulfillJson(route, currentPractice),
  );

  await mockEndpoint(page, "GET", "/api/ai/thread/messages", (route) =>
    fulfillJson(route, [
      {
        id: "44444444-4444-4444-8444-444444444444",
        role: "assistant",
        content: "Let us work through the workload conversation.",
        userName: "Maya Chen",
      },
      {
        id: "55555555-5555-4555-8555-555555555555",
        role: "user",
        content: "I need help prioritizing the work that is already committed.",
        userName: null,
      },
    ]),
  );

  await mockEndpoint(page, "GET", "/api/env/luma", (route) =>
    fulfillJson(route, {
      enabled: false,
      courseGenerationEnabled: false,
      voiceMentorEnabled: false,
      voiceTtsProvider: "cartesia",
    }),
  );

  await mockEndpoint(
    page,
    "POST",
    `/api/ai/judge/${AI_MENTOR_PRACTICE_THREAD_ID}`,
    async (route) => {
      currentPractice = {
        ...currentPractice,
        evaluation: AI_MENTOR_PRACTICE_EVALUATION,
        threadStatus: "completed",
      };
      await fulfillJson(route, AI_MENTOR_PRACTICE_EVALUATION);
    },
  );

  await mockEndpoint(
    page,
    "POST",
    `/api/ai/practice/${AI_MENTOR_PRACTICE_ID}/replay`,
    async (route) => {
      await replayReleased;
      currentPractice = { ...READY_AI_MENTOR_PRACTICE, evaluation: null };
      await fulfillJson(route, currentPractice);
    },
  );

  return { releaseReplay: () => releaseReplay() };
};
